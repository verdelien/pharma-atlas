#!/usr/bin/env python3
"""Merge research/data/*.json into pipeline.js (loaded by index.html and zh.html).
usage: python3 research/build.py   (run from the repo root or anywhere)"""
import json, os, glob, re

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
out = {}
for f in sorted(glob.glob(os.path.join(here, "data", "*.json"))):
    d = json.load(open(f, encoding="utf-8"))
    cid = d.get("id") or os.path.basename(f)[:-5]
    for it in d.get("items") or []:
        n = it.get("next")
        if isinstance(n, dict) and not (n.get("en") or "").strip():
            it["next"] = None
        if isinstance(it.get("src"), str):
            it["src"] = re.sub(r"[?&]trk=[^&#]*", "", it["src"])
    for w in d.get("watch") or []:
        if isinstance(w.get("src"), str):
            w["src"] = re.sub(r"[?&]trk=[^&#]*", "", w["src"])
    d["sources"] = [[s[0], re.sub(r"[?&]trk=[^&#]*", "", s[1])] for s in d.get("sources") or [] if isinstance(s, list) and len(s) == 2]
    out[cid] = d
js = ("// Generated by research/build.py from research/data/*.json. Do not edit by hand.\n"
      "window.PIPE=" + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
open(os.path.join(root, "pipeline.js"), "w", encoding="utf-8").write(js)
print(f"pipeline.js: {len(out)} companies, {sum(len(d.get('items') or []) for d in out.values())} items, {len(js)//1024} KB")
