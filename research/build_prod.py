#!/usr/bin/env python3
"""Merge research/prod/*.json (verified product revenue / LOE) into prodfix.js, applied by the pages at load."""
import json, os, glob
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here)
out = {}
for f in sorted(glob.glob(os.path.join(here, "prod", "*.json"))):
    d = json.load(open(f, encoding="utf-8")); cid = d.get("id") or os.path.basename(f)[:-5]
    rows = [r for r in d.get("rows") or [] if r.get("v") is not None or any(l.get("value") for l in r.get("loe") or [])]
    if rows or d.get("new_products"):
        out[cid] = {"rows": rows, "new_products": d.get("new_products") or []}
js = "// Generated by research/build_prod.py from research/prod/*.json. Do not edit by hand.\nwindow.PRODFIX=" + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
open(os.path.join(root, "prodfix.js"), "w", encoding="utf-8").write(js)
print(f"prodfix.js: {len(out)} companies, {sum(len(v['rows']) for v in out.values())} rows, {sum(len(v['new_products']) for v in out.values())} new products")
